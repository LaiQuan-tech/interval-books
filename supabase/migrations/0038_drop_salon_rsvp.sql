-- 0037 為城市思享沙龍另開了一張 salon_rsvps，理由寫在那一支的 §0：那一場是不收錢的
-- 審核邀請制，塞進 event_registrations 要生假訂單、要在回覆的當下就佔掉名額。
--
-- 那個判斷在「回條」這個框架下是對的，但它換掉了一件更重要的事：**名單不在後台**。
-- /admin/registrations 已經有完整的名單介面（逐位參加者、揭露聯絡方式、CSV 匯出、
-- 單筆移除），而 salon_rsvps 沒有任何後台，只能下 SQL 看。為了保住四個額外欄位
-- （服務單位／職稱／期待題目／婉拒選項），代價是整套既有的名單工具都用不到。
--
-- 所以這一場改走既有流程：一件 price=0 的 event 商品 + 一個 15 席的場次，報名經過
-- 結帳（0028 的 settle_free_order() 會把 total=0 的訂單當場結清），名單直接進
-- event_registrations，後台當場看得到。額外欄位由結帳頁既有的「備註」承接
-- （orders.note，後台訂單詳情看得到）；「遺憾不克前往」這個選項沒有對應概念，
-- 不報名就是不來。
--
-- ⚠️ 這張表**從來沒有存過任何一筆正式資料**。上線後只做過一次端到端驗證，那一列
--    在驗完當下就刪掉了；drop 之前確認過 count = 0。所以這裡直接 drop，不做備份表。
--
-- ═══════════════════════════════════════════════════════════════════════════

drop table if exists public.salon_rsvps;
